#!/usr/bin/env python3
"""Keep every README C# block compile-checked in existing console/ASP.NET examples. Never executes examples."""
import re,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1];readme=(root/'README.md').read_text()
blocks=dict(re.findall(r'<!-- example: ([a-z]+) -->\s*```csharp\n(.*?)\n```',readme,re.S))
if set(blocks)!={'console','aspnet','resources','errors'} or readme.count('```csharp')!=len(blocks):raise SystemExit('Every C# block needs a supported example marker')
outputs={'examples/Kirora.Examples/Program.cs':blocks['console']+'\n','examples/Kirora.AspNetCore/Program.cs':blocks['aspnet']+'\n'}
source='// <auto-generated>Compile checks for the exact README snippets; helpers are never invoked automatically.</auto-generated>\n#nullable enable\nusing Kirora;\nusing Kirora.Models;\nusing Kirora.Exceptions;\n\nnamespace Kirora.Examples;\n\ninternal static class ReadmeExamples\n{\n'
for name in ['resources','errors']:
 body='\n'.join(line for line in blocks[name].splitlines() if not line.startswith('using '))
 source+='    internal static async Task '+name.title()+'Async(KiroraClient kirora, CancellationToken token)\n    {\n'+'\n'.join('        '+line if line else '' for line in body.splitlines())+'\n    }\n'
source+='}\n';outputs['examples/Kirora.Examples/ReadmeExamples.g.cs']=source
for name,content in outputs.items():
 p=root/name
 if '--write' in sys.argv:p.write_text(content)
 elif not p.exists() or p.read_text()!=content:raise SystemExit('README compile fixture is stale: '+name+'; run python3 tools/check-readme.py --write')
print('All four README C# blocks match compile-checked example sources. Build the solution to verify compilation; no code was executed.')
