#!/usr/bin/env python3
"""Generate the small foundation model subset from the checksum-pinned official spec."""
import hashlib
import json
from pathlib import Path
import sys
from codegen_xml import document

root = Path(__file__).resolve().parents[1]
raw = (root / 'spec/openapi.json').read_bytes()
source = json.loads((root / 'spec/source.json').read_text())
if hashlib.sha256(raw).hexdigest() != source['sha256']:
    raise SystemExit('Pinned specification checksum does not match spec/source.json')
spec = json.loads(raw)
if spec['info']['version'] != source['version']:
    raise SystemExit('Pinned specification version mismatch')
if spec['paths']['/v1/me']['get']['operationId'] != 'getMe':
    raise SystemExit('The expected official operation is missing')
schemas = spec['components']['schemas']
classes = []

def pascal(name):
    return name[0].upper() + name[1:]

def generate(name, schema):
    if schema.get('type') != 'object':
        raise ValueError('Unsupported root schema: ' + name)
    members = []
    for field, shape in schema['properties'].items():
        required = field in schema.get('required', [])
        nullable = False
        if 'anyOf' in shape:
            choices = shape['anyOf']
            nonnull = [x for x in choices if x.get('type') != 'null']
            if len(choices) != 2 or len(nonnull) != 1:
                raise ValueError('Unsupported anyOf: ' + field)
            shape, nullable = nonnull[0], True
        kind = shape.get('type')
        if kind == 'object':
            typename = name + pascal(field)
            generate(typename, shape)
        elif kind == 'string':
            typename = 'Guid' if shape.get('format') == 'uuid' else 'string'
        elif kind == 'number':
            typename = 'double'
        elif kind == 'array' and shape['items'].get('type') == 'string':
            typename = 'IReadOnlyList<string>'
        else:
            raise ValueError(f'Unsupported model construct: {name}.{field}: {shape}')
        if nullable or not required:
            typename += '?'
        modifier = 'required ' if required else ''
        members.append(f'    [JsonPropertyName("{field}")]')
        if not required:
            members.append('    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]')
        members.extend([f'    public {modifier}{typename} {pascal(field)} {{ get; init; }}', ''])
    classes.append(f'public sealed partial class {name}\n{{\n' + '\n'.join(members) + '}\n')

for name in ['ApiCaller', 'FieldError']:
    generate(name, schemas[name])
content = '// <auto-generated>From the checksum-pinned Kirora OpenAPI spec; run tools/generate-foundation-models.py.</auto-generated>\n#nullable enable\nusing System.Text.Json.Serialization;\n\nnamespace Kirora.Models;\n\n' + '\n'.join(classes)
content = document(content)
target = root / 'src/Kirora/Models/FoundationModels.g.cs'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('Generated foundation models are stale')
    print('Foundation models match the pinned specification.')
else:
    target.write_text(content)
    print('Generated ApiCaller, nested workspace/key models and FieldError.')
